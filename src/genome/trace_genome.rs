//! The fugue trace encoding of genomes (`ppl` feature).
//!
//! This module is the boundary between the classic evolutionary-computation
//! layer and the PPL-native inference layer: a genome that implements
//! [`TraceGenome`] can be round-tripped through a [`fugue::Trace`] and
//! therefore driven by the trace-space machinery in
//! [`crate::inference`] (MH rejuvenation, tempered SMC, block regeneration).
//!
//! The encoding produced by [`TraceGenome::to_trace`] is *canonical* — an
//! address→value map at the genome's site addresses (`gene#i`, `bit#i`,
//! `perm#i`, …) with zero stored log-probabilities. Probability mass is never
//! carried by this encoding; it is recovered by scoring the trace under a
//! genuine prior model (see [`crate::inference::prior::GenomePrior`]), which is also
//! how the inference layer decodes a genome from a particle
//! (`decode`-by-replay).

use fugue::{addr, Address, Trace};

// Re-export ChoiceValue for use in genome trace implementations (relocated
// from `genome::traits` when the trait was split).
pub use fugue::ChoiceValue;

use rand::Rng;
use serde::{de::DeserializeOwned, Serialize};

use crate::error::GenomeError;
use crate::genome::bounds::MultiBounds;
use crate::genome::traits::EvolutionaryGenome;

/// Extension trait: genomes that can be encoded as fugue traces.
///
/// Implementing this trait is what admits a genome to the `ppl` inference
/// layer. The classic algorithms never require it.
pub trait TraceGenome: EvolutionaryGenome {
    /// Convert genome to a fugue trace.
    ///
    /// Each gene is stored at an indexed address (e.g., `gene#0`, `gene#1`, …)
    /// as a pure value; stored log-probabilities are zero. Score the trace
    /// under a prior model to obtain real probability mass.
    fn to_trace(&self) -> Trace;

    /// Reconstruct genome from a fugue trace.
    ///
    /// This is the inverse of [`Self::to_trace`], extracting gene values from
    /// the trace's choice map.
    fn from_trace(trace: &Trace) -> Result<Self, GenomeError>;

    /// Get the address prefix used for trace storage (default: `"gene"`).
    fn trace_prefix() -> &'static str {
        "gene"
    }
}

/// Helper function to create a gene address for trace storage
pub fn gene_address(prefix: &str, index: usize) -> Address {
    addr!(prefix, index)
}

/// A genome that exists only as the **return value of a prior program**: it
/// is generated by running a [`GenomePrior`](crate::inference::prior::GenomePrior),
/// decoded from a particle or chain state by replaying that program, and
/// encoded back by the prior's own
/// [`trace_of`](crate::inference::prior::GenomePrior::trace_of). It has no
/// canonical `gene#i` encoding and no classical operators.
///
/// Implementing this marker is the light way into the `ppl` inference layer.
/// [`GenomePrior::Genome`](crate::inference::prior::GenomePrior::Genome) is
/// bounded by [`TraceGenome`], whose supertrait is the whole classical
/// [`EvolutionaryGenome`] surface (`Allele`, `Phenotype`, `decode`,
/// `dimension`, `generate`, `distance`, `try_distance`, `to_trace`,
/// `from_trace`). A `ReplayGenome` gets both traits from the blanket impls
/// below and writes none of those methods:
///
/// ```rust
/// use fugue_evo::genome::trace_genome::{ReplayGenome, TraceGenome};
/// use fugue_evo::genome::traits::EvolutionaryGenome;
/// use serde::{Deserialize, Serialize};
///
/// /// A program in some downstream DSL, built only by a grammar prior.
/// #[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
/// struct Program(Vec<String>);
///
/// impl ReplayGenome for Program {
///     fn replay_dimension(&self) -> usize {
///         self.0.len()
///     }
/// }
///
/// let p = Program(vec!["push".into(), "add".into()]);
/// // Both layer traits are now implemented.
/// assert_eq!(p.dimension(), 2);
/// assert_eq!(p.decode(), p);
/// // There is no canonical encoding: the prior's `trace_of` supplies one.
/// assert!(p.to_trace().choices.is_empty());
/// assert!(Program::from_trace(&p.to_trace()).is_err());
/// // No distance is defined, and the fallible form says so.
/// assert!(p.try_distance(&p).is_err());
/// ```
///
/// # What the blanket impls do
///
/// | Method | Behaviour for a `ReplayGenome` |
/// |---|---|
/// | `Allele` / `Phenotype` | `()` / `Self` |
/// | `decode` | `self.clone()` |
/// | `dimension` | [`Self::replay_dimension`] (default `0`) |
/// | `to_trace` | the **empty** trace: scoring it through a prior reports the first site as [`GenomeError::MissingAddress`] instead of a wrong density |
/// | `from_trace` | `Err(GenomeError::InvalidStructure)`: decode by replaying the prior |
/// | `try_distance` | `Err(GenomeError::InvalidStructure)` |
/// | `distance` | **panics** (the trait forbids a silent fallback distance) |
/// | `generate` | **panics**: a replay-only genome is drawn from its prior, not from `MultiBounds` |
///
/// The two panicking methods are reached only from the classic layer
/// (`classic` feature); nothing in [`crate::inference`] calls them. A genome
/// that should also run under the classic algorithms implements
/// [`EvolutionaryGenome`] and [`TraceGenome`] by hand instead of this marker.
///
/// # The serde bound
///
/// `Serialize + DeserializeOwned` is a supertrait of [`EvolutionaryGenome`]
/// and therefore of anything usable as a `GenomePrior::Genome`; this marker
/// cannot waive it. Dropping it needs a weaker bound on
/// `GenomePrior::Genome`, which is a breaking change.
pub trait ReplayGenome: Clone + Send + Sync + Serialize + DeserializeOwned + 'static {
    /// A size for the genome, reported by
    /// [`EvolutionaryGenome::dimension`]. Defaults to `0`.
    fn replay_dimension(&self) -> usize {
        0
    }
}

const REPLAY_ONLY: &str = "replay-only genome (ReplayGenome)";

impl<T: ReplayGenome> EvolutionaryGenome for T {
    type Allele = ();
    type Phenotype = T;

    fn decode(&self) -> T {
        self.clone()
    }

    fn dimension(&self) -> usize {
        self.replay_dimension()
    }

    /// # Panics
    ///
    /// Always: a replay-only genome is generated by running its
    /// [`GenomePrior`](crate::inference::prior::GenomePrior).
    fn generate<R: Rng>(_rng: &mut R, _bounds: &MultiBounds) -> Self {
        panic!("{REPLAY_ONLY}: generate it by running its GenomePrior, not from MultiBounds")
    }

    /// # Panics
    ///
    /// Always: no distance is defined. Use [`EvolutionaryGenome::try_distance`] for an
    /// error instead.
    fn distance(&self, _other: &Self) -> f64 {
        panic!("{REPLAY_ONLY}: no distance is defined")
    }

    fn try_distance(&self, _other: &Self) -> Result<f64, GenomeError> {
        Err(GenomeError::InvalidStructure(format!(
            "{REPLAY_ONLY}: no distance is defined"
        )))
    }
}

impl<T: ReplayGenome> TraceGenome for T {
    fn to_trace(&self) -> Trace {
        Trace::default()
    }

    fn from_trace(_trace: &Trace) -> Result<Self, GenomeError> {
        Err(GenomeError::InvalidStructure(format!(
            "{REPLAY_ONLY}: decode it by replaying its GenomePrior over the trace"
        )))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde::Deserialize;

    #[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
    struct Word(Vec<u8>);

    impl ReplayGenome for Word {
        fn replay_dimension(&self) -> usize {
            self.0.len()
        }
    }

    #[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
    struct Unit;
    impl ReplayGenome for Unit {}

    #[test]
    fn test_replay_genome_gets_both_layer_traits() {
        fn needs_trace_genome<G: TraceGenome>(_g: &G) {}
        let w = Word(vec![1, 2, 3]);
        needs_trace_genome(&w);
        assert_eq!(w.dimension(), 3);
        assert_eq!(Unit.dimension(), 0);
        assert_eq!(w.decode(), w);
        assert!(w.as_slice().is_none());
        assert!(w.to_trace().choices.is_empty());
        assert!(matches!(
            Word::from_trace(&Trace::default()),
            Err(GenomeError::InvalidStructure(_))
        ));
        assert!(matches!(
            w.try_distance(&w),
            Err(GenomeError::InvalidStructure(_))
        ));
        assert_eq!(Word::trace_prefix(), "gene");
    }

    #[test]
    #[should_panic(expected = "no distance is defined")]
    fn test_replay_genome_distance_panics() {
        let w = Word(vec![1]);
        let _ = w.distance(&w);
    }

    #[test]
    #[should_panic(expected = "generate it by running its GenomePrior")]
    fn test_replay_genome_generate_panics() {
        let mut rng = rand::thread_rng();
        let _ = Word::generate(&mut rng, &MultiBounds::symmetric(1.0, 1));
    }

    /// The empty canonical encoding is rejected by replay scoring with an
    /// error naming the first site, never scored as a density.
    #[test]
    fn test_replay_genome_canonical_trace_is_rejected_by_scoring() {
        use fugue::{sample, Bernoulli};
        let model = sample(addr!("x"), Bernoulli::new(0.5).unwrap());
        let err = crate::inference::smc::score_genome(&Unit, model).unwrap_err();
        assert!(matches!(err, GenomeError::MissingAddress(_)), "{err:?}");
    }
}
